const WEED_VALUES = new Set(TURF_WEED_OPTIONS.map(option => option.value))
const TIMING_VALUES = new Set(WEED_CONTROL_TIMINGS.map(option => option.value))

function makeId() {
  return `weed-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 7)}`
}

export function weedLabel(value) {
  return TURF_WEED_OPTIONS.find(option => option.value === value)?.label ?? value
}

export function weedControlTimingLabel(value) {
  return WEED_CONTROL_TIMINGS.find(option => option.value === value)?.label ?? value
}

export function makeWeedTarget() {
  return {
    id: makeId(),
    weed: '',
    timing: 'post_emergent',
  }
}

export function normalizeWeedTargets(value, options = {}) {
  let rows = value
  if (typeof rows === 'string') {
    try { rows = JSON.parse(rows) } catch { rows = [] }
  }
  if (!Array.isArray(rows)) return []
  const keepEmpty = Boolean(options.keepEmpty)

  return rows
    .map(row => {
      const rawWeed = String(row?.weed ?? '').trim()
      const weed = WEED_VALUES.has(rawWeed) ? rawWeed : rawWeed
      const timing = TIMING_VALUES.has(row?.timing) ? row.timing : 'post_emergent'
      return {
        id: row?.id || makeId(),
        weed,
        timing,
      }
    })
    .filter(row => keepEmpty || row.weed)
}

export function formatWeedTargetSummary(value) {
  const rows = normalizeWeedTargets(value)
  if (rows.length === 0) return ''
  return rows
    .map(row => `${weedLabel(row.weed)} (${weedControlTimingLabel(row.timing).toLowerCase()})`)
    .join(', ')
}
